"""Sends a JOB1 sample bank to BREAK SURGEON over USB-MIDI SysEx (docs/development/sample-format.md).

    jo_send_bank.py BANK [--port NAME]          send it (needs: pip3 install mido python-rtmidi)
    jo_send_bank.py BANK --host-script OUT.txt  the same frames as a script for fm1-base's host simulator,
                                                with the device's expected answers (tests/host/)

The FM-1 must be stopped (not playing): the loader erases flash sectors as it writes, which stalls the audio.
STATUS: the protocol and the device's loader are tested in the host simulator; a transfer to a physical FM-1
has NOT been tested yet. The bank lives in the data area (0xA1000..0xDBFFF), apart from the firmware and from
the factory calibration; a failed transfer leaves the firmware working with its built-in test break.
"""
import argparse, sys, time

HDR = [0xF0, 0x7D, 0x4A, 0x42]
CHUNK = 512  # payload bytes per DATA frame: 512 -> 586 bytes of SysEx, under fm1-base's 640-byte frame


def u35(v):
    return [(v >> (7 * i)) & 0x7F for i in range(5)]


def pack7(data):
    """per 7 bytes: a byte of their high bits (bit i = byte i's), then the 7 low-7-bit bytes"""
    out = []
    for i in range(0, len(data), 7):
        g = data[i:i + 7]
        out.append(sum(((b >> 7) & 1) << j for j, b in enumerate(g)))
        out.extend(b & 0x7F for b in g)
    return out


def frames(img):
    yield HDR + [0x01] + u35(len(img)) + [0xF7], (0x01, 0, len(img))
    for off in range(0, len(img), CHUNK):
        chunk = img[off:off + CHUNK]
        yield HDR + [0x02] + u35(off) + pack7(chunk) + [0xF7], (0x02, 0, off + len(chunk))
    yield HDR + [0x03, 0xF7], (0x03, 0, None)


def reply(cmd, status, value):
    return HDR + [0x7F, cmd, status] + u35(value or 0) + [0xF7]


def hexs(b):
    return " ".join(f"{x:02X}" for x in b)


def host_script(img, path):
    with open(path, "w") as f:
        f.write("# generated by tools/sample-prep/jo_send_bank.py --host-script: a bank transfer, frame by frame\n")
        f.write("wait 500\nsysex_out\n")
        for fr, (cmd, st, val) in frames(img):
            f.write(f"sysex {hexs(fr)}\nwait 5\n")
            if val is not None:
                f.write(f"expect_sysex {hexs(reply(cmd, st, val))}\n")
            f.write("sysex_out\n")


def send(img, port_name):
    import mido  # only for a real transfer
    names = [n for n in mido.get_output_names() if (port_name or "BREAK SURGEON") in n]
    if not names:
        raise SystemExit(f"no MIDI port named like {port_name or 'BREAK SURGEON'}: {mido.get_output_names()}")
    with mido.open_output(names[0]) as out, mido.open_input([n for n in mido.get_input_names() if names[0][:12] in n][0]) as inp:
        for fr, (cmd, st, val) in frames(img):
            out.send(mido.Message("sysex", data=fr[1:-1]))
            t0 = time.time()
            while True:
                m = inp.poll()
                if m is not None and m.type == "sysex" and list(m.data[:5]) == HDR[1:] + [0x7F] and m.data[5] == cmd:
                    if m.data[6]:
                        raise SystemExit(f"the FM-1 refused (command {cmd}, status {m.data[6]}): see sample-format.md")
                    break
                if time.time() - t0 > 3:
                    raise SystemExit(f"no answer to command {cmd}")
                time.sleep(0.001)
            if cmd == 0x02:
                print(f"\r{val} / {len(img)} bytes", end="", flush=True)
    print("\nloaded")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bank")
    ap.add_argument("--port")
    ap.add_argument("--host-script")
    a = ap.parse_args()
    img = open(a.bank, "rb").read()
    if img[:4] != b"JOB1":
        raise SystemExit(f"{a.bank}: not a JOB1 bank (tools/sample-prep/jo_sample_prep.py build)")
    if a.host_script:
        host_script(img, a.host_script)
    else:
        send(img, a.port)


if __name__ == "__main__":
    sys.exit(main())
